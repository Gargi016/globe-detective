export const HISTORICAL_EVENTS: readonly HistoricalEvent[] = [
  ...SOVIET,
  ...CENTRAL_EUROPE,
  ...BALKANS,
  ...ASIA,
  ...AFRICA,
  ...AMERICAS_OCEANIA,
];

const BY_ID = new Map(HISTORICAL_EVENTS.map((e) => [e.id, e]));

export function getEvent(id: string): HistoricalEvent | undefined {
  return BY_ID.get(id);
}

export function eventsByCategory(category: EventCategory): HistoricalEvent[] {
  return HISTORICAL_EVENTS.filter((e) => e.category === category);
}

/** Case-insensitive search by subject, title or alias. */
export function searchEvents(query: string, limit = 12): HistoricalEvent[] {
  const q = query.trim().toLowerCase();
  if (q === '') return [];
  const scored: { e: HistoricalEvent; score: number }[] = [];
  for (const e of HISTORICAL_EVENTS) {
    let score = 0;
    for (const a of e.aliases) {
      if (a === q) score = Math.max(score, 100);
      else if (a.startsWith(q)) score = Math.max(score, 60);
      else if (a.includes(q)) score = Math.max(score, 30);
    }
    if (e.subject.toLowerCase().includes(q)) score = Math.max(score, 25);
    if (e.title.toLowerCase().includes(q)) score = Math.max(score, 10);
    if (score > 0) scored.push({ e, score });
  }
  return scored.sort((a, b) => b.score - a.score).slice(0, limit).map((s) => s.e);
}
