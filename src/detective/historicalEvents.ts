import type {
  DatePrecision,
  DateRange,
  EventCategory,
  EvidenceQuality,
  HistoricalEvent,
  IsoDate,
  OmissionRisk,
  SourceRef,
} from './types';

/**
 * Structured historical event database.
 *
 * Each record states one *depiction* a globe can carry and the periods during which a globe that is up to
 * date would carry it. Bounds are widened, never narrowed, wherever a date is gradual or disputed, so that
 * the database never excludes a date that might be right (such records are marked `approximate`).
 *
 * Curation notes
 *  - Dates are written from the cited references. Phase 4 did NOT re-open every source page: before relying on
 *    a date for scholarly work, check it against the linked source. `scripts/verify-events.ts` cross-checks
 *    the state-level dates against the CShapes 2.0 data the app already ships.
 *  - Absence is weaker than presence, so every record carries an `omissionRisk` used when a globe is seen to
 *    *lack* something.
 *  - Records that are mutually exclusive depictions of one thing (old name / new name) share a `group`.
 */

const wiki = (title: string, label?: string): SourceRef => ({
  label: `${label ?? title.replace(/_/g, ' ')} (Wikipedia)`,
  url: `https://en.wikipedia.org/wiki/${title}`,
});

const R = (start: IsoDate | null, end: IsoDate | null): DateRange => ({ start, end });

interface Spec {
  id: string;
  cat: EventCategory;
  subject: string;
  title: string;
  desc: string;
  valid: DateRange[];
  date: IsoDate;
  src: SourceRef[];
  aliases: string[];
  prec?: DatePrecision;
  q?: EvidenceQuality;
  risk?: OmissionRisk;
  group?: string;
  gw?: number;
  open?: string;
  notes?: string;
}

const ev = (s: Spec): HistoricalEvent => ({
  id: s.id,
  category: s.cat,
  subject: s.subject,
  title: s.title,
  description: s.desc,
  valid: s.valid,
  eventDate: s.date,
  precision: s.prec ?? 'day',
  quality: s.q ?? 'documented',
  openStartNote: s.open,
  aliases: s.aliases,
  omissionRisk: s.risk ?? 'low',
  group: s.group,
  gw: s.gw,
  sources: s.src,
  notes: s.notes,
});

