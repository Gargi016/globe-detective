    check('removed printed card', pg.locator('.evidence').count()==2)
    print('== estimate')
    pg.get_by_role('button',name='Run estimate').first.click(); pg.wait_for_timeout(400)
    t=txt()
    check('verdict range', '1971' in pg.inner_text('.verdict__range'), pg.inner_text('.verdict__range'))
    check('exact dates', '26 Mar 1971' in t and '21 May 1972' in t)
    check('likely / possible', 'Most likely made' in t and 'Possibly as late as' in t)
    check('confidence both', 'Confidence in the map-content date' in t and 'Confidence in the manufacture date' in t)
    check('reasoning steps', pg.locator('.reasoning__step').count()==2)
    check('deciding clue tags', pg.locator('.reasoning__binding').count()==2)
    check('caveats', 'Limits of this estimate' in t)
    check('range bar', pg.locator('.rangebar__seg').count()>=2)
    pg.locator('.confidence__factors summary').first.click(); check('factors expandable', 'How narrow the range is' in txt())
