import re, sys
from playwright.sync_api import sync_playwright
A=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']
fails=[]
def check(name, cond, detail=''):
    print(('  ok   ' if cond else '  FAIL ')+name+(f' [{detail}]' if (detail and not cond) else ''))
    if not cond: fails.append(name)
with sync_playwright() as p:
    b=p.chromium.launch(args=A)
    ctx=b.new_context(viewport={'width':1300,'height':900})
    pg=ctx.new_page(); pg.set_default_timeout(90000)
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto('http://localhost:4173/#/detective'); pg.wait_for_selector('.desk__panel', state='attached'); pg.wait_for_timeout(3000)
    tab=lambda n: pg.get_by_role('tab',name=re.compile(n)).click()
    txt=lambda: pg.inner_text('.desk__panel')
    print('== fresh desk')
    check('heading', 'investigation' in pg.inner_text('h1').lower())
    check('progress starts at 0', '0 of 5' in txt().lower())
    check('run disabled with no observations', pg.get_by_role('button',name='Run estimate').first.is_disabled())
    print('== search and add')
    pg.fill('#clue-search','ceylon'); pg.wait_for_timeout(300)
    check('ceylon result', 'Labels the island nation as Ceylon' in txt())
    pg.get_by_role('button',name='What happened?').first.click()
    check('event description + sources', 'Dominion of Ceylon' in txt() and 'Wikipedia' in txt())
    pg.get_by_role('button',name='My globe shows this').first.click(); pg.wait_for_timeout(200)
    check('notice after add', 'Added to the case file' in txt())
    check('button now marked added', pg.get_by_role('button',name='✓ Globe shows this').count()>=1)
    check('progress advanced', '2 of 5' in txt().lower(), txt()[:120])
    pg.fill('#clue-search','bangladesh'); pg.wait_for_timeout(300)
