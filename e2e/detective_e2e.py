    pg.get_by_role('button',name='Run estimate').first.click(); pg.wait_for_timeout(300)
    check('cold war range 1949-1972', '1949' in pg.inner_text('.verdict__range') and '1972' in pg.inner_text('.verdict__range'), pg.inner_text('.verdict__range'))
    pg.get_by_role('button',name='Soviet Union').first.click(); pg.wait_for_timeout(2500)
    t=txt(); check('selecting a case file state suggests clues', 'On the globe:' in t and 'Clues linked to' in t, t[:200])
    pg.get_by_role('button',name='Browse' if False else 'All').first.click() if pg.get_by_role('button',name='All').count() else None
    pg.get_by_role('button',name='Capital change').click(); pg.wait_for_timeout(200)
    check('browse by category', pg.locator('.result').count()>=5)
    pg.get_by_role('button',name=re.compile('Show more')).first.click(); pg.wait_for_timeout(100)
