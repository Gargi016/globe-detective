    tab('Case file'); pg.wait_for_timeout(200)
    check('two evidence cards', pg.locator('.evidence').count()==2, str(pg.locator('.evidence').count()))
    check('tab count', 'Case file (2)' in txt())
    check('progress 3 of 5', '3 of 5' in txt().lower())
    print('== modify / remove')
    card=pg.locator('.evidence').nth(0)
    card.locator('select').first.select_option('uncertain'); pg.wait_for_timeout(150)
    check('certainty changed', card.locator('select').first.input_value()=='uncertain')
    card.get_by_role('button',name='Missing from globe').click(); pg.wait_for_timeout(150)
    check('toggled to missing', 'does not show' in pg.locator('.evidence').nth(0).inner_text().lower() or 'Does not show' in pg.locator('.evidence').nth(0).inner_text())
    pg.locator('.evidence').nth(0).get_by_role('button',name='Shown on globe').click(); pg.wait_for_timeout(150)
    pg.locator('.evidence').nth(0).locator('input.select').last.fill('top-left of the Indian Ocean'); pg.wait_for_timeout(100)
    check('note kept', pg.locator('.evidence').nth(0).locator('input.select').last.input_value()=='top-left of the Indian Ocean')
    print('== printed date')
    tab('Search')
    pg.locator('.printed input').first.fill('12'); pg.get_by_role('button',name='Add printed date').click()
    check('bad year rejected', 'four-digit' in txt())
    pg.locator('.printed input').first.fill('1975'); pg.get_by_role('button',name='Add printed date').click(); pg.wait_for_timeout(200)
    tab('Case file'); check('printed card present', pg.locator('.evidence').count()==3 and 'Printed date 1975' in txt())
