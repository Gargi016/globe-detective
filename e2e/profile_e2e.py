import re, json
from playwright.sync_api import sync_playwright
A=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']
fails=[]
def check(n,c,d=''):
    print(('  ok   ' if c else '  FAIL ')+n+(f' [{d}]' if (d and not c) else ''))
    if not c: fails.append(n)
with sync_playwright() as p:
    b=p.chromium.launch(args=A)
    ctx=b.new_context(viewport={'width':1300,'height':900}, accept_downloads=True)
    pg=ctx.new_page(); pg.set_default_timeout(90000)
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    body=lambda: pg.inner_text('body').lower()
    print('== empty profile')
    pg.goto('http://localhost:4173/#/profile'); pg.wait_for_selector('.profile',state='attached')
    check('nav link', pg.locator('.nav__link',has_text='Profile').count()==1)
    check('default name', 'anonymous detective' in pg.inner_text('[data-testid=profile-name]').lower())
    check('rank apprentice', 'apprentice' in pg.inner_text('[data-testid=profile-rank]').lower())
    check('zero stats', pg.inner_text('[data-testid=stat-points]')=='0' and pg.inner_text('[data-testid=stat-completed]')=='0')
    check('0 of 12 badges', '0 of 12' in pg.inner_text('[data-testid=ach-count]'))
    check('no-leaderboard note', 'no global leaderboard' in body())
    print('== rename/emblem')
    pg.get_by_role('button',name='Rename').click(); pg.fill('#profile-name','Ada Lovelace'); pg.get_by_role('button',name='Save').click()
    check('renamed', 'ada lovelace' in pg.inner_text('[data-testid=profile-name]').lower())
    pg.get_by_role('button',name='Globe',exact=True).click()
    check('emblem pressed', pg.get_by_role('button',name='Globe',exact=True).get_attribute('aria-pressed')=='true')
    pg.reload(); pg.wait_for_selector('.profile',state='attached')
    check('persisted', 'ada lovelace' in pg.inner_text('[data-testid=profile-name]').lower())
    print('== detective -> badge')
    pg.goto('http://localhost:4173/#/detective'); pg.wait_for_selector('.desk__panel',state='attached'); pg.wait_for_timeout(3000)
    for q in ['ceylon','bangladesh','east germany']:
        pg.fill('#clue-search',q); pg.wait_for_timeout(300)
        pg.get_by_role('button',name='My globe shows this').first.click(); pg.wait_for_timeout(200)
    pg.get_by_role('button',name='Run estimate').first.click(); pg.wait_for_timeout(800)
    check('toast first investigation', pg.locator('[data-testid=achievement-toast]',has_text='First Investigation').count()==1)
    pg.locator('[data-testid=achievement-toast] a').first.click(); pg.wait_for_selector('.profile',state='attached'); pg.wait_for_timeout(300)
    check('badge unlocked', pg.get_by_test_id('badge-first-investigation').get_attribute('data-unlocked')=='true')
    check('investigations stat 1', pg.inner_text('[data-testid=stat-investigations]')=='1')
    check('investigation row', pg.locator('[data-testid=investigation-history] .hrow').count()==1)
    print('== reopen')
    pg.get_by_role('button',name='Reopen in Detective').click(); pg.wait_for_selector('.desk__panel',state='attached'); pg.wait_for_timeout(2500)
    check('hash detective', pg.evaluate('location.hash')=='#/detective')
    check('case restored', 'restored' in pg.inner_text('.desk__panel').lower() and 'case file (3)' in pg.inner_text('.desk__panel').lower())
    print('== challenge')
    pg.goto('http://localhost:4173/#/challenge'); pg.wait_for_selector('.cmenu',state='attached'); pg.wait_for_function("!document.querySelector('.level .btn').disabled")
    pg.get_by_role('button',name='Play Easy').click(); pg.wait_for_selector('.play',state='attached')
    pg.fill('.guess__input','1950'); pg.get_by_role('button',name='Submit guess').click(); pg.wait_for_selector('.result',state='attached'); pg.wait_for_timeout(500)
    check('case opened toast', pg.locator('[data-testid=achievement-toast]',has_text='Case Opened').count()==1)
    pg.goto('http://localhost:4173/#/profile'); pg.wait_for_selector('.profile',state='attached'); pg.wait_for_timeout(300)
    check('completed 1', pg.inner_text('[data-testid=stat-completed]')=='1')
    check('history row', pg.locator('[data-testid=challenge-history] .hrow').count()==1)
    check('points match', pg.inner_text('[data-testid=stat-points]')==pg.inner_text('[data-testid=stat-best]'))
    print('== export')
    with pg.expect_download() as dl: pg.get_by_role('button',name='Export my data').click()
    data=json.load(open(dl.value.path()))
    check('export content', data['profile']['name']=='Ada Lovelace' and len(data['challenge']['history'])==1)
    print('== history years via timeline')
    pg.goto('http://localhost:4173/#/timeline?year=1965'); pg.wait_for_selector('.timebar',state='attached'); pg.wait_for_timeout(3000)
    pg.goto('http://localhost:4173/#/profile'); pg.wait_for_selector('.profile',state='attached')
    check('years explored >=1', int(re.search(r'years explored\s*(\d+)', pg.inner_text('[data-testid=stats]').lower().replace('\n',' ')).group(1))>=1)
    print('== delete / clear / erase')
    pg.get_by_role('button',name=re.compile('^Delete')).first.click()
    check('entry deleted, count kept', pg.locator('[data-testid=investigation-history]').count()==0 and pg.inner_text('[data-testid=stat-investigations]')=='1')
    check('badge survives', pg.get_by_test_id('badge-first-investigation').get_attribute('data-unlocked')=='true')
    pg.get_by_role('button',name='Erase all local data').click(); pg.get_by_role('button',name='Yes, erase everything').click(); pg.wait_for_timeout(500)
    check('erased', 'anonymous detective' in pg.inner_text('[data-testid=profile-name]').lower() and pg.inner_text('[data-testid=stat-completed]')=='0')
    check('badges reset', '0 of 12' in pg.inner_text('[data-testid=ach-count]'))
    print('== mobile')
    pg.set_viewport_size({'width':390,'height':800})
    for r in ['profile','home','detective','challenge','about']:
        pg.goto(f'http://localhost:4173/#/{r}'); pg.wait_for_timeout(800)
        w=pg.evaluate('document.documentElement.scrollWidth')
        check(f'no overflow {r}', w<=390, str(w))
    check('no page errors', not errs, str(errs[:2]))
    b.close()
print('FAILS:',fails)
