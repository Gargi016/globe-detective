import re, sys
from playwright.sync_api import sync_playwright
A=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']
fails=[]
def check(name, cond, detail=''):
    print(('  ok   ' if cond else '  FAIL ')+name+(f' [{detail}]' if (detail and not cond) else ''), flush=True)
    if not cond: fails.append(name)
def pts(d):
    return 100 if d==0 else 95 if d==1 else 80 if d<=5 else 60 if d<=10 else 30 if d<=20 else 10
with sync_playwright() as p:
    b=p.chromium.launch(args=A); ctx=b.new_context(viewport={'width':1300,'height':900})
    pg=ctx.new_page(); pg.set_default_timeout(90000); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    body=lambda: pg.inner_text('main').lower()
    def open_menu():
        pg.goto('http://localhost:4173/#/challenge'); pg.wait_for_selector('.cmenu',state='attached'); pg.wait_for_function("!document.querySelector('.level .btn').disabled")
    open_menu()
    print('== menu')
    check('daily card', 'daily challenge' in body() and pg.get_by_role('button',name='Play today’s globe').is_enabled())
    check('three difficulties', pg.locator('.level').count()==3)
    check('scoring table 6 rows', pg.locator('.scoretable tbody tr').count()==6)
    check('empty record', 'no challenges played yet' in body())
    print('== easy round')
    pg.get_by_role('button',name='Play Easy').click(); pg.wait_for_selector('.play',state='attached')
    check('play screen', 'mystery globe' in body())
    check('year hidden', 'reference date' not in body() and not re.search(r'case closed', body()))
    pg.get_by_role('button',name='Submit guess').click(); check('empty guess rejected', 'four-digit year' in body())
    pg.fill('.guess__input','62'); pg.get_by_role('button',name='Submit guess').click(); check('short guess rejected', 'four-digit year' in body())
    pg.locator('.guess__slider').fill('1975'); check('slider sets the input', pg.input_value('.guess__input')=='1975')
    check('4 hints available', 'of 4 used' in body())
    for i in range(4):
        pg.get_by_role('button',name=re.compile('Reveal hint')).click(); pg.wait_for_timeout(100)
    check('four hints shown', pg.locator('.hint').count()==4 and 'no hints left' in body())
    check('hint text is real', 'the map was drawn for a date between' in body() and 'areas are drawn' in body())
    print('== resume after reload')
    pg.reload(); pg.wait_for_selector('.cmenu',state='attached')
    check('resume offered', 'challenge in progress' in body())
    pg.wait_for_function("!document.querySelector('.level .btn').disabled")
    pg.get_by_role('button',name='Continue').click(); pg.wait_for_selector('.play',state='attached')
    check('hints and guess preserved', pg.locator('.hint').count()==4 and pg.input_value('.guess__input')=='1975', pg.input_value('.guess__input'))
    print('== submit')
    pg.fill('.guess__input','1960'); pg.get_by_role('button',name='Submit guess').click(); pg.wait_for_selector('.result',state='attached')
    t=pg.inner_text('.result'); low=t.lower()
    check('completion screen', 'case closed' in low and 'reference date' in low and 'why this span' in low)
    interval=pg.inner_text('.result__wide dd')
    yrs=[int(x) for x in re.findall(r'\b(1[89]\d\d|20[01]\d)\b', interval)]
    start,end=yrs[0],yrs[-1]
    dist=0 if start<=1960<=end else min(abs(1960-start),abs(1960-end))
    shown=int(re.search(r'(\d+)',pg.inner_text('.result__points')).group(1))
    check(f'score matches table (interval {start}-{end}, distance {dist})', shown==pts(dist), f'shown {shown} expected {pts(dist)}')
    check('scoring row highlighted', pg.locator('.scoretable tr.is-active').count()==1)
    check('historical clues listed', pg.locator('.result .results .result').count()>=1)
    check('hints used recorded', 'hints used' in low and '4' in t)
    check('streak panel', 'streak' in low and 'total' in low)
    print('== another / skip / leave')
    pg.get_by_role('button',name='Play another challenge').click(); pg.wait_for_selector('.play',state='attached')
    check('new round has no hints', pg.locator('.hint').count()==0 and 'easy' in body())
    pg.get_by_role('button',name=re.compile('Skip')).click(); pg.wait_for_timeout(500)
    check('skip gives a fresh globe', pg.locator('.hint').count()==0 and pg.locator('.play').count()==1)
    pg.get_by_role('button',name=re.compile('Back to menu')).click(); pg.wait_for_selector('.cmenu',state='attached')
    check('history shows the round', pg.locator('.hrow').count()==1 and 'played' in body())
    print('== daily')
    pg.get_by_role('button',name='Continue').click(); pg.wait_for_selector('.play',state='attached')
    pg.get_by_role('button',name=re.compile('Back to menu')).click()
    pg.get_by_role('button',name='Play today’s globe').click(); pg.wait_for_selector('.play',state='attached')
    check('daily badge, no skip', pg.locator('.play__head .cat--independence').count()==1 and pg.get_by_role('button',name=re.compile('Skip')).count()==0)
    pg.fill('.guess__input','1991'); pg.get_by_role('button',name='Submit guess').click(); pg.wait_for_selector('.result',state='attached')
    check('daily result', 'daily' in pg.inner_text('.result').lower() and 'daily streak' in pg.inner_text('.result').lower())
    pg.get_by_role('button',name='Menu and history').click(); pg.wait_for_selector('.cmenu',state='attached')
    check('daily done today', 'completed today' in body() and pg.get_by_role('button',name='Done for today').is_disabled())
    check('daily streak 1', re.search(r'daily streak: 1', body()) is not None)
    check('two rounds in history', pg.locator('.hrow').count()==2)
    print('== persistence, hard, reset')
    pg.reload(); pg.wait_for_selector('.cmenu',state='attached')
    check('history survives reload', pg.locator('.hrow').count()==2 and 'completed today' in body())
    pg.wait_for_function("!document.querySelector('.level .btn').disabled")
    pg.get_by_role('button',name='Play Hard').click(); pg.wait_for_selector('.play',state='attached')
    check('hard: 2 hints, names hidden note', 'of 2 used' in body())
    pg.get_by_role('button',name=re.compile('Back to menu')).click()
    pg.get_by_role('button',name='Reset my progress').click(); check('reset asks to confirm', 'erase history' in body())
    pg.get_by_role('button',name='Cancel').click(); check('cancel keeps history', pg.locator('.hrow').count()==2)
    pg.get_by_role('button',name='Reset my progress').click(); pg.get_by_role('button',name='Yes, erase').click(); pg.wait_for_timeout(300)
    check('reset clears history', 'no challenges played yet' in body() and 'challenge in progress' not in body())
    pg.reload(); pg.wait_for_selector('.cmenu',state='attached')
    check('reset persisted', 'no challenges played yet' in body() and pg.get_by_role('button',name='Play today’s globe').is_enabled() is not None)
    pg.set_viewport_size({'width':390,'height':800}); pg.wait_for_timeout(500)
    check('mobile menu no overflow', pg.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 1'))
    check('no page errors', not errs, str(errs))
    b.close()
print('\nFAILURES:', fails if fails else 'none', flush=True)
